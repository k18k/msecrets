import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { describe, test } from "node:test";

import { armor, decryptAge, encryptAge } from "../src/crypto/age.ts";
import { scryptRecipient } from "../src/crypto/age-recipients.ts";
import { ed25519Verify, supportsMlKem } from "../src/crypto/primitives.ts";
import {
  formatIdentityFile,
  generateIdentity,
  identityMatches,
  isMsecretsError,
  parseIdentities,
  parseIdentity,
  parsePublicKey,
  readOnlyPublicKey,
} from "../src/index.ts";
import { readOnlyToken } from "./helpers.ts";

const SSH = join(import.meta.dirname, "fixtures", "ssh");
const unsupported = (error: unknown) =>
  isMsecretsError(error, "UNSUPPORTED") && /Node\.js >= 24\.7/.test(error.message);
const ssh = (name: string) => readFileSync(join(SSH, name), "utf8");

describe("age identities", () => {
  for (const postQuantum of [false, true]) {
    const label = postQuantum ? "post-quantum" : "classic";
    const skip = postQuantum && !supportsMlKem() ? "ML-KEM unsupported" : false;

    test(`${label}: generate, serialize, parse, encrypt, decrypt, sign`, { skip }, () => {
      const identity = generateIdentity({ postQuantum });
      assert.match(
        identity.secret,
        postQuantum ? /^AGE-SECRET-KEY-PQ-1[0-9A-Z]+$/ : /^AGE-SECRET-KEY-1[0-9A-Z]+$/,
      );
      assert.match(identity.publicKey.token, /^msecrets1[0-9a-z]+$/);
      assert.equal(identity.publicKey.postQuantum, postQuantum);

      const parsed = parseIdentity(identity.secret);
      assert.equal(parsed.publicKey.token, identity.publicKey.token);

      const publicKey = parsePublicKey(identity.publicKey.token);
      assert.ok(identityMatches(identity, publicKey));
      const ciphertext = encryptAge(Buffer.from("hello"), [publicKey.recipient]);
      assert.equal(decryptAge(ciphertext, [parsed.ageIdentity]).toString(), "hello");

      const signature = parsed.sign(Buffer.from("message"));
      assert.ok(
        publicKey.signingKey &&
          ed25519Verify(publicKey.signingKey, Buffer.from("message"), signature),
      );
      assert.ok(!ed25519Verify(publicKey.signingKey, Buffer.from("other"), signature));
    });
  }

  test(
    "post-quantum keys on a runtime without ML-KEM fail with a clear error",
    { skip: supportsMlKem() ? "ML-KEM is supported here" : false },
    () => {
      assert.throws(() => generateIdentity({ postQuantum: true }), unsupported);
      assert.throws(
        () =>
          parseIdentity(
            "AGE-SECRET-KEY-PQ-1XX76JRALNLXDMEW0CRK45QMCCH4X06SE84UN3VPM33W6HWDX0H3SK3ZQFR",
          ),
        unsupported,
      );
      const recipient = parsePublicKey(
        readFileSync(join(import.meta.dirname, "fixtures", "pq-recipient.txt"), "utf8"),
      );
      assert.equal(
        recipient.postQuantum,
        true,
        "parsing post-quantum public keys works everywhere",
      );
      assert.throws(() => encryptAge(Buffer.from("x"), [recipient.recipient]), unsupported);
    },
  );

  test(
    "post-quantum key derivation matches the age specification",
    { skip: supportsMlKem() ? false : "ML-KEM unsupported" },
    () => {
      const identity = parseIdentity(
        "AGE-SECRET-KEY-PQ-1XX76JRALNLXDMEW0CRK45QMCCH4X06SE84UN3VPM33W6HWDX0H3SK3ZQFR",
      );
      const expected = readFileSync(
        join(import.meta.dirname, "fixtures", "pq-recipient.txt"),
        "utf8",
      ).trim();
      assert.equal(readOnlyPublicKey(identity.publicKey).token, expected);
    },
  );

  test("plain age1 recipients are read-only and match the same identity", () => {
    const identity = generateIdentity();
    const readOnly = parsePublicKey(readOnlyToken(identity));
    assert.equal(readOnly.signingKey, null);
    assert.equal(readOnly.kind, "x25519");
    assert.ok(identityMatches(identity, readOnly));
    assert.equal(
      decryptAge(encryptAge(Buffer.from("x"), [readOnly.recipient]), [
        identity.ageIdentity,
      ]).toString(),
      "x",
    );
  });

  test("identities generated by age-keygen are accepted", () => {
    const identity = parseIdentity(
      "AGE-SECRET-KEY-1GFPYYSJZGFPYYSJZGFPYYSJZGFPYYSJZGFPYYSJZGFPYYSJZGFPQ4EGAEX",
    );
    assert.equal(
      readOnlyToken(identity),
      "age1zvkyg2lqzraa2lnjvqej32nkuu0ues2s82hzrye869xeexvn73equnujwj",
    );
  });

  test("rejects malformed keys with clear errors", () => {
    const identity = generateIdentity();
    for (const bad of [
      "",
      "hello",
      "AGE-SECRET-KEY-1abc",
      identity.secret.slice(0, -1),
      identity.publicKey.token.toUpperCase().slice(0, -2),
    ]) {
      assert.throws(
        () => parseIdentity(bad),
        (error: unknown) => isMsecretsError(error, "INVALID_KEY"),
        bad,
      );
    }
    const token = identity.publicKey.token;
    const tampered = `${token.slice(0, -1)}${token.endsWith("q") ? "p" : "q"}`;
    for (const bad of ["", "age1", "msecrets1qqqq", tampered, "ssh-ed25519", "ssh-ed25519 AAAA"]) {
      assert.throws(
        () => parsePublicKey(bad),
        (error: unknown) => isMsecretsError(error),
        bad,
      );
    }
  });

  test("the same key never yields two different tokens", () => {
    const identity = generateIdentity();
    assert.equal(parsePublicKey(identity.publicKey.token).token, identity.publicKey.token);
    assert.equal(parsePublicKey(` ${identity.publicKey.token}\n`).token, identity.publicKey.token);
  });
});

describe("SSH keys", () => {
  test("unencrypted ed25519 key: identity, public key, and signatures", () => {
    const identity = parseIdentity(ssh("plain"));
    const publicKey = parsePublicKey(ssh("plain.pub"));
    assert.equal(identity.kind, "ssh-ed25519");
    assert.equal(identity.publicKey.token, publicKey.token);
    assert.ok(!publicKey.token.includes("plain@test"), "comments are not part of the token");
    assert.ok(identityMatches(identity, publicKey));
    assert.equal(
      decryptAge(encryptAge(Buffer.from("ssh"), [publicKey.recipient]), [
        identity.ageIdentity,
      ]).toString(),
      "ssh",
    );
    assert.ok(
      publicKey.signingKey &&
        ed25519Verify(publicKey.signingKey, Buffer.from("m"), identity.sign(Buffer.from("m"))),
    );
  });

  for (const name of ["encrypted-ctr", "encrypted-gcm"]) {
    test(`passphrase-protected key (${name})`, () => {
      assert.throws(() => parseIdentity(ssh(name)), /passphrase-protected/);
      assert.throws(
        () => parseIdentity(ssh(name), { passphrase: () => "wrong" }),
        /Incorrect passphrase/,
      );
      const identity = parseIdentity(ssh(name), { passphrase: () => "correct horse" });
      assert.equal(identity.publicKey.token, parsePublicKey(ssh(`${name}.pub`)).token);
    });
  }

  test("RSA keys are reported as unsupported", () => {
    assert.throws(
      () => parsePublicKey(ssh("rsa.pub")),
      (error: unknown) => isMsecretsError(error, "UNSUPPORTED"),
    );
    assert.throws(
      () => parseIdentity(ssh("rsa")),
      (error: unknown) => isMsecretsError(error, "UNSUPPORTED"),
    );
  });

  test("rejects an ed25519 public key that is not on the curve", () => {
    const wire = Buffer.concat([
      Buffer.from([0, 0, 0, 11]),
      Buffer.from("ssh-ed25519"),
      Buffer.from([0, 0, 0, 32]),
      Buffer.alloc(32, 0xff),
    ]);
    assert.throws(
      () => parsePublicKey(`ssh-ed25519 ${wire.toString("base64")}`),
      /Invalid Ed25519 public key/,
    );
  });
});

describe("identity files", () => {
  test("parse comments, blank lines, CRLF, and several identities", () => {
    const first = generateIdentity();
    const second = generateIdentity();
    const text = `${formatIdentityFile(first, "laptop")}\r\n\r\n# another\r\n${second.secret}\r\n`;
    assert.deepEqual(
      parseIdentities(text).map((identity) => identity.publicKey.token),
      [first.publicKey.token, second.publicKey.token],
    );
  });

  test("passphrase-encrypted identity files, binary and armored", () => {
    const identity = generateIdentity();
    const encrypted = encryptAge(Buffer.from(formatIdentityFile(identity)), [
      scryptRecipient("hunter2", 10),
    ]);
    for (const contents of [encrypted, armor(encrypted)]) {
      assert.throws(() => parseIdentities(contents), /passphrase-encrypted/);
      assert.throws(
        () => parseIdentities(contents, { passphrase: () => "wrong" }),
        (error: unknown) => isMsecretsError(error, "AGE_NO_MATCH"),
      );
      assert.equal(
        parseIdentities(contents, { passphrase: () => "hunter2" })[0]?.publicKey.token,
        identity.publicKey.token,
      );
    }
  });

  test("an empty file is an error", () => {
    assert.throws(() => parseIdentities("# nothing here\n"), /No identities found/);
  });
});
